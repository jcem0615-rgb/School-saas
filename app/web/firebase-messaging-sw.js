// Background handler for web push.
//
// The page's own Dart code only runs while a tab is open. This worker is
// what the browser wakes when the app is closed or backgrounded -- which
// is the entire point of the feature: a class-suspension notice is
// useless if it only appears to people already looking at the app.
//
// Loaded by the Firebase SDK by convention from the site root; the name
// is not ours to choose. The compat builds are used because a service
// worker has no module loader.
importScripts('https://www.gstatic.com/firebasejs/10.12.2/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.12.2/firebase-messaging-compat.js');

// Fill these in from your Firebase console (Project settings > General >
// Your apps > SDK setup and configuration). They are all public
// identifiers -- the same values already shipped inside main.dart.js --
// and none of them grant access on their own; firestore.rules does that.
//
// This file is NOT generated by flutterfire configure, so it has to be
// filled in by hand once per project.
firebase.initializeApp({
  apiKey: 'REPLACE_ME',
  authDomain: 'REPLACE_ME.firebaseapp.com',
  projectId: 'REPLACE_ME',
  storageBucket: 'REPLACE_ME.appspot.com',
  messagingSenderId: 'REPLACE_ME',
  appId: 'REPLACE_ME',
});

const messaging = firebase.messaging();

// Notifications sent with a `notification` payload are displayed by the
// browser on their own; this handler exists so a data-only message still
// surfaces, and so the tap target is the announcements screen rather than
// whatever page happened to be open.
messaging.onBackgroundMessage((payload) => {
  const title = (payload.notification && payload.notification.title) || 'Announcement';
  const body = (payload.notification && payload.notification.body) || '';
  self.registration.showNotification(title, {
    body,
    icon: '/icons/Icon-192.png',
    badge: '/icons/Icon-192.png',
    data: {link: (payload.fcmOptions && payload.fcmOptions.link) || '/#/announcements'},
  });
});

// Focus an already-open tab instead of piling up new ones each time
// somebody taps a notification.
self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const link = (event.notification.data && event.notification.data.link) || '/#/announcements';
  event.waitUntil(
    clients.matchAll({type: 'window', includeUncontrolled: true}).then((windowClients) => {
      for (const client of windowClients) {
        if ('focus' in client) {
          client.navigate(link);
          return client.focus();
        }
      }
      return clients.openWindow(link);
    })
  );
});
